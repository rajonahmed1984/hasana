    // Asked of every day, on top of the day's own amal
    private const DAILY_AMAL = 'সকাল-সন্ধ্যার জিকির ও পাঁচ ওয়াক্ত নামাজ সময়মতো আদায় করুন';

    /**
     * @return array{day:int, month:int, year:int, month_bn:string, label:string}
     */
    public static function hijri(CarbonInterface $date): array
    {
        // Noon UTC of the local calendar date, shifted by the moon-sighting offset (Bangladesh is often a day behind)
        $day = Carbon::create($date->year, $date->month, $date->day, 12, 0, 0, 'UTC')
            ->addDays((int) config('app.hijri_offset', 0));

        [$d, $m, $y] = self::intlHijri($day) ?? self::tabularHijri($day);
        $monthBn = self::HIJRI_MONTHS_BN[$m];

        return [
            'day' => $d,
            'month' => $m,
            'year' => $y,
            'month_bn' => $monthBn,
            'label' => self::bnDigits($d).' '.$monthBn.' '.self::bnDigits($y).' হিজরি',
        ];
    }

    /**
     * Keys of all occasions that apply to the date, most important first.
     *
     * @return list<string>
     */
    public static function occasionKeys(CarbonInterface $date): array
    {
        ['day' => $d, 'month' => $m] = self::hijri($date);
        $noFasting = ($m === 10 && $d === 1) || ($m === 12 && $d >= 10 && $d <= 13);

        $keys = [];
        if ($m === 10 && $d === 1) $keys[] = 'eid_ul_fitr';
        if ($m === 12 && $d === 10) $keys[] = 'eid_ul_adha';
        if ($m === 12 && $d === 9) $keys[] = 'arafah';
        if ($m === 12 && $d >= 11 && $d <= 13) $keys[] = 'tashriq';
        if ($m === 1 && ($d === 9 || $d === 10)) $keys[] = 'ashura';
        if ($m === 9) $keys[] = $d >= 21 ? 'ramadan_last_ten' : 'ramadan';
        if ($m === 12 && $d <= 8) $keys[] = 'dhul_hijjah';
        if ($date->isFriday()) $keys[] = 'jumuah';
        if ($d >= 13 && $d <= 15 && $m !== 9 && ! $noFasting) $keys[] = 'ayyam_bid';
        if ($m === 10 && $d >= 2) $keys[] = 'shawwal';
        if ($m === 1 && $d !== 9 && $d !== 10) $keys[] = 'muharram';
        if ($m === 8) $keys[] = 'shaban';
        if (($date->isMonday() || $date->isThursday()) && $m !== 9 && ! $noFasting) $keys[] = 'mon_thu';

        return $keys;
    }

    /**
     * [surah_number, ayah_number] for a special day, or null on an ordinary day.
     */
    public static function ayahRef(CarbonInterface $date): ?array
    {
        $key = self::occasionKeys($date)[0] ?? null;

        return $key ? self::OCCASIONS[$key]['ayah'] : null;
    }

    /**
     * Occasion, hadith and amal list for the date.
     */
    public static function forDate(CarbonInterface $date): array
    {
        $keys = self::occasionKeys($date);
        $primary = $keys ? self::OCCASIONS[$keys[0]] : null;

        if ($primary) {
            $hadith = $primary['hadith'];
            $amal = $primary['amal'];
        } else {
            $general = self::GENERAL[(int) $date->format('z') % count(self::GENERAL)];
            $amal = [$general['amal']];
            unset($general['amal']);
            $hadith = $general;
        }

        // Add the first deed of every other occasion of the day (e.g. Jumu'ah in Ramadan)
        foreach (array_slice($keys, 1) as $key) {
            $amal[] = self::OCCASIONS[$key]['amal'][0];
        }
        $amal = array_slice(array_values(array_unique($amal)), 0, 5);
        $amal[] = self::DAILY_AMAL;

        return [
            'hijri' => self::hijri($date),
            'occasion' => $primary ? [
                'key' => $keys[0],
                'title' => $primary['title'],
                'others' => array_map(fn ($k) => self::OCCASIONS[$k]['title'], array_slice($keys, 1)),
            ] : null,
            'hadith' => $hadith,
            'amal' => $amal,
        ];
    }

    private static function intlHijri(CarbonInterface $day): ?array
    {
        if (! class_exists(\IntlDateFormatter::class)) {
            return null;
        }

        $formatter = new \IntlDateFormatter(
            'en_US@calendar=islamic-umalqura',
            \IntlDateFormatter::NONE,
            \IntlDateFormatter::NONE,
            'UTC',
            \IntlDateFormatter::TRADITIONAL,
            'd/M/y'
        );
        $out = $formatter->format($day->getTimestamp());

        return $out && preg_match('/^(\d+)\/(\d+)\/(\d+)$/', $out, $m) ? [(int) $m[1], (int) $m[2], (int) $m[3]] : null;
    }

    /**
     * Arithmetic (tabular) Islamic calendar, for servers without the intl extension.
     */
    private static function tabularHijri(CarbonInterface $day): array
    {
        $a = intdiv(14 - $day->month, 12);
        $y = $day->year + 4800 - $a;
        $m = $day->month + 12 * $a - 3;
        $jdn = $day->day + intdiv(153 * $m + 2, 5) + 365 * $y + intdiv($y, 4) - intdiv($y, 100) + intdiv($y, 400) - 32045;

        $l = $jdn - 1948440 + 10632;
        $n = intdiv($l - 1, 10631);
        $l = $l - 10631 * $n + 354;
        $j = intdiv(10985 - $l, 5316) * intdiv(50 * $l, 17719) + intdiv($l, 5670) * intdiv(43 * $l, 15238);
        $l = $l - intdiv(30 - $j, 15) * intdiv(17719 * $j, 50) - intdiv($j, 16) * intdiv(15238 * $j, 43) + 29;
        $month = intdiv(24 * $l, 709);
        $dayOfMonth = $l - intdiv(709 * $month, 24);

        return [$dayOfMonth, $month, 30 * $n + $j - 30];
    }

    private static function bnDigits(int $n): string
    {
        return strtr((string) $n, ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯']);
    }
